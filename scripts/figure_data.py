"""README şekillerinin verisini üretir — ölçümden, elle kopyalamadan.

Kaynak tek: `scripts/tani_esdogrusallik_96.py`'nin ürettiği JSON, o da
üretim havuzunun CSV'sinden okur. Şekillerde görünen hiçbir sayı elle
yazılmaz; yazılsaydı şekil ile kayıt sessizce ayrışırdı — bu deponun
2. tur dersi: *aynı büyüklük iki yerde yazılıysa ve biri türetilmiyorsa,
er geç ayrışır.*

    python scripts/tani_esdogrusallik_96.py \\
        docs/sonuclar/havuz_posterior_girdi.csv \\
        --json docs/figures/data/identifiability.json
    python scripts/figure_data.py
    make -C docs/figures

Üretilenler (hepsi `docs/figures/data/`):

- `shrink.tex` — `identifiability.tex`'in çizdiği geometri. Posteriorun
  önsele göre genişliği, üç ana yönde. Şekil bu dosyayı `\\input` eder,
  yani diskteki elipsoit **ölçümün kendisidir**.
- `validation_rows.tex` — çapraz kod kıyasının üç satırı.
- `validation.dat` — aynı kıyas, insan okusun diye düz metin.

`validation` sayıları KAYIT-067'den gelir ve burada **açıkça** yazılıdır,
çünkü o ölçüm bu JSON'da değil kilitli kayıttadır. Oran `beta` değil
**`beta - 1`** üzerindendir (eklenen momentumun kendisi); KAYIT-067
tablosu da öyle.
"""
from __future__ import annotations

import json
import math
import pathlib
import statistics
import sys

KOK = pathlib.Path(__file__).resolve().parents[1]
VERI = KOK / "docs" / "figures" / "data"
KAYNAK = VERI / "identifiability.json"

sys.path.insert(0, str(KOK / "src"))

from dartrift.inference.tanimlanabilirlik import (  # noqa: E402
    FISHER_ESIGI,
    ONSEL_VARYANS,
)

#: KAYIT-067 W2 tablosu: `Y0` [Pa], bizim `beta`, L1 Tablo 2.
KIYAS = ((50, 3.295, 3.63), (10, 3.667, 4.18), (1, 3.992, 4.66))


def _genislik(lam: float) -> float:
    """Posterior sd / önsel sd, tek bir ana yönde.

    `fisher_yonleri` ile **aynı** formül: `sd = 1/sqrt(lam + 1/onsel)`.
    Burada yeniden türetilmesinin sebebi, şeklin çizdiği uzunluğun
    çıkarımın kullandığı sayıyla aynı tanımdan gelmesidir.
    """
    p = 1.0 / ONSEL_VARYANS
    return math.sqrt(p / (lam + p))


def main() -> None:
    if not KAYNAK.exists():
        raise SystemExit(
            f"BOSLUK: {KAYNAK} yok.\n"
            "Once: python scripts/tani_esdogrusallik_96.py "
            "docs/sonuclar/havuz_posterior_girdi.csv "
            f"--json {KAYNAK}")
    d = json.loads(KAYNAK.read_text(encoding="utf-8"))
    pts = sorted(d["noktalar"], key=lambda p: p["kuresel"])
    n = len(pts)
    if n != 96:
        raise SystemExit(f"KURAL 8: 96 nokta bekleniyordu, {n} okundu")

    # --- sekil 1: posteriorun onsele gore genisligi ------------------
    # Ucuncu yon TAM 1'dir ve bu bir yuvarlama degil: iki gozlenebilir,
    # uc bilinmeyen -> Fisher matrisinin rank'i en cok 2, yani ucuncu oz
    # deger sifir ve o yonde onsel hic daralmaz.
    g1 = statistics.median(_genislik(float(p["oz1"])) for p in pts)
    g2 = statistics.median(_genislik(float(p["oz2"])) for p in pts)
    g3 = _genislik(0.0)
    ust_sinir = min(2, 3)   # gozlenebilir sayisi, parametre sayisi

    (VERI / "shrink.tex").write_text(
        "% GENERATED by scripts/figure_data.py -- do not edit by hand.\n"
        "% Posterior width relative to the prior, along the three\n"
        "% principal directions; median over the 96 design points.\n"
        f"% The third is exactly {g3:.3f} by rank: {ust_sinir} observables\n"
        "% cannot constrain 3 unknowns.\n"
        f"\\def\\THIN{{{g1:.3f}}}\n"
        f"\\def\\WIDE{{{g2:.3f}}}\n"
        f"\\def\\FREE{{{g3:.3f}}}\n",
        encoding="utf-8")

    # --- sekil 2: capraz kod kiyasi ----------------------------------
    vs = ["% GENERATED by scripts/figure_data.py -- do not edit by hand.",
          "% \\vrow{row}{beta ours}{beta Raducan}{Y0 label}{ratio on beta-1}",
          ""]
    for i, (y0, bizim, l1) in enumerate(KIYAS):
        vs.append(f"\\vrow{{{i}}}{{{bizim}}}{{{l1}}}{{{y0}}}"
                  f"{{{(bizim - 1.0) / (l1 - 1.0):.3f}}}")
    (VERI / "validation_rows.tex").write_text("\n".join(vs) + "\n",
                                              encoding="utf-8")

    with (VERI / "validation.dat").open("w", encoding="utf-8") as f:
        f.write("# GENERATED by scripts/figure_data.py from KAYIT-067 (W2)\n")
        f.write("# ratio is on beta-1, not beta.\n")
        f.write("Y0 ours raducan ratio\n")
        for y0, bizim, l1 in KIYAS:
            f.write(f"{y0} {bizim} {l1} {(bizim - 1.0) / (l1 - 1.0):.4f}\n")

    # --- ozet ---------------------------------------------------------
    oz = d["ozet"]
    gecen1 = sum(1 for p in pts if float(p["oz1"]) >= FISHER_ESIGI)
    gecen2 = sum(1 for p in pts if float(p["oz2"]) >= FISHER_ESIGI)
    print("=" * 62)
    print("README sekil verisi")
    print("=" * 62)
    print(f"kaynak         : {KAYNAK.name}  ({n} nokta)")
    print(f"esik           : {FISHER_ESIGI}  (PROTOKOL-UP, kilitli)")
    print(f"esigi gecen    : lambda1 {gecen1}/{n}   lambda2 {gecen2}/{n}")
    print(f"lambda2 maks   : {oz['ikinci_ozdeger']['maks']:.3f}")
    print()
    print("posterior genisligi / onsel genisligi:")
    print(f"  birinci yon  : {g1:.3f}")
    print(f"  ikinci yon   : {g2:.3f}")
    print(f"  ucuncu yon   : {g3:.3f}   (rank geregi TAM)")
    print()
    print(f"yazildi        : {VERI}")


if __name__ == "__main__":
    sys.exit(main() or 0)
